// Ad-hoc sign the macOS app after packaging. Without any signature, Apple silicon
// reports downloaded apps as "damaged"; with an ad-hoc signature users get the normal
// "unverified developer" prompt and can use System Settings → Open Anyway.
const { execFileSync } = require('node:child_process');
const path = require('node:path');

exports.default = async function afterPack(context) {
  if (context.electronPlatformName !== 'darwin') return;
  const app = path.join(context.appOutDir, `${context.packager.appInfo.productFilename}.app`);
  execFileSync('codesign', ['--force', '--deep', '--sign', '-', app], { stdio: 'inherit' });
  execFileSync('codesign', ['--verify', '--deep', '--strict', '--verbose=2', app], { stdio: 'inherit' });
};
